update public.news_articles
set
  source_published_at = coalesce(source_published_at, published_at),
  normalized_source_url = coalesce(normalized_source_url, canonical_url),
  ingested_at = coalesce(fetched_at, created_at, now()),
  dedup_status = case
    when duplicate_of is not null then 'duplicate'
    else 'skipped'
  end,
  publication_status = case
    when duplicate_of is not null then 'duplicate'
    when status = 'processed' then 'published'
    when status = 'failed' then 'failed'
    else 'processing'
  end;

