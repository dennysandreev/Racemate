create or replace function public.acquire_news_dedup_lock(
  p_lock_key text,
  p_article_id uuid,
  p_stale_after_seconds integer default 300
)
returns boolean
language plpgsql
security invoker
set search_path = public
as $$
begin
  insert into public.news_dedup_locks (
    lock_key,
    article_id,
    acquired_at,
    expires_at
  )
  values (
    p_lock_key,
    p_article_id,
    now(),
    now() + make_interval(secs => greatest(30, least(coalesce(p_stale_after_seconds, 300), 1800)))
  )
  on conflict (lock_key) do update
  set
    article_id = excluded.article_id,
    acquired_at = excluded.acquired_at,
    expires_at = excluded.expires_at
  where
    public.news_dedup_locks.expires_at <= now()
    or public.news_dedup_locks.article_id = excluded.article_id;

  return found;
end;
$$;

create or replace function public.release_news_dedup_lock(
  p_lock_key text,
  p_article_id uuid
)
returns boolean
language plpgsql
security invoker
set search_path = public
as $$
declare
  deleted_count integer;
begin
  delete from public.news_dedup_locks
  where lock_key = p_lock_key
    and article_id = p_article_id;

  get diagnostics deleted_count = row_count;
  return deleted_count > 0;
end;
$$;

