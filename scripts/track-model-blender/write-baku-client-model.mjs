import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

export async function writeBakuClientModel() {
  const [config, metadata, asset] = await Promise.all([
    readFile(path.join(root, ".track-model-build/baku.json"), "utf8").then(JSON.parse),
    readFile(path.join(root, "public/f1/tracks/3d/baku-metadata.json"), "utf8").then(JSON.parse),
    readFile(path.join(root, "public/f1/tracks/3d/baku.glb")),
  ]);
  const round = (value, digits = 4) => Number(value.toFixed(digits));
  const total = metadata.lapLength.geometryMeters;
  const profile = metadata.elevationProfile;
  const slopes = profile.slice(1).map((p, i) => (p.elevationMeters - profile[i].elevationMeters) / Math.max(p.distanceMeters - profile[i].distanceMeters, .001) * 100);
  const points = metadata.replayGeometry.track.map((p) => p.map((v) => round(v, 6)));
  points.at(-1).splice(0, 4, 1, ...points[0].slice(1));
  const turns = config.model.turns.map(({ number, distanceMeters }) => ({ number, progress: round(distanceMeters / total, 6) }));
  const data = {
    circuitName: "Baku City Circuit", lapLengthKm: 6.003,
    elevationChangeM: round(metadata.elevationsMeters.high - metadata.elevationsMeters.low, 1),
    maxDownhillPercent: round(Math.abs(Math.min(...slopes)), 1), maxUphillPercent: round(Math.max(...slopes), 1),
    points, turns, sectorBreaks: metadata.sectorBoundaryDistancesMeters.map((d) => round(d / total, 6)),
    speedTrapProgress: round((config.model.turns[19].distanceMeters + 210) / total, 6),
  };
  const terrain = {
    attribution: "Planet SkySat · 09.04.2018 · CC BY-SA 4.0 · OpenStreetMap · GEDTM30 (приблизительные высоты)",
    attributionUrl: "https://commons.wikimedia.org/wiki/File:Baku_City_Circuit,_April_9,_2018_SkySat.jpg",
    bounds: { minX: -1, minY: -1, maxX: 1, maxY: 1 }, columns: 2, rows: 2,
    elevationMinM: metadata.elevationsMeters.low, elevationMaxM: metadata.elevationsMeters.high,
    values: [[metadata.elevationsMeters.low, metadata.elevationsMeters.high], [metadata.elevationsMeters.high, metadata.elevationsMeters.low]],
  };
  const revision = createHash("sha256").update(asset).digest("hex").slice(0, 12);
  const model = {
    id: "baku", aliases: ["baku city circuit", "baku", "баку", "azerbaijan grand prix", "гран-при азербайджана"],
    camera: { centerY: 0, rotationDeg: 0, scale: 1, tiltDeg: 10, verticalExaggeration: 1 },
    data: "__DATA__", terrain: "__TERRAIN__",
    rendering: { contourIntervalM: 5, curbTurnNumbers: turns.map((t) => t.number), gravelTurnNumbers: [], runoffTurnNumbers: [], turnLabelOffsets: Object.fromEntries(turns.map((t) => [t.number, [0, 0]])) },
    webgl: { assetPath: `/f1/tracks/3d/baku.glb?v=${revision}`, previewPath: "/f1/tracks/3d/baku-preview.webp", turnCount: 20, elevationDatumLabel: "м DEM", elevationApproximate: true, camera: { fitWidth: 5500, fitHeight: 3600, lookAtY: 18, radius: 3400 } },
  };
  const replay = { baseElevationMeters: metadata.baseElevationMeters, pitLanePoints: metadata.replayGeometry.pit, startFinishProgress: 0, surfaceOffsetMeters: .4, trackPoints: points, trackWidthMeters: 12 };
  const output = `import type { TrackModelDefinition } from "@/data/track-model-types";\n\n// Generated by pnpm track:3d:build baku. Metre geometry; approximate GEDTM elevations.\nexport const BAKU_MODEL = ${JSON.stringify(data, null, 2)} as const;\n\nexport const BAKU_TERRAIN = ${JSON.stringify(terrain, null, 2)} as const;\n\nexport const BAKU_REPLAY_PATH = ${JSON.stringify(replay, null, 2)} as const;\n\nexport const BAKU_TRACK_MODEL = ${JSON.stringify(model, null, 2).replace('"__DATA__"', "BAKU_MODEL").replace('"__TERRAIN__"', "BAKU_TERRAIN")} satisfies TrackModelDefinition;\n`;
  await writeFile(path.join(root, "src/data/baku-model.ts"), output);
}
