import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export async function writeMadringClientModel({ configPath, metadataPath, outputPath = path.join(root, "src/data/madring-model.ts") }) {
  const [config, metadata] = await Promise.all([configPath, metadataPath].map(async (file) => JSON.parse(await readFile(file, "utf8"))));
  const assetRevision = createHash("sha256").update(await readFile(path.join(path.dirname(metadataPath), "madring.glb"))).digest("hex").slice(0, 12);
  const profile = metadata.elevationProfile;
  const total = metadata.geometry.lengthMeters;
  const round = (x, places = 3) => Number(x.toFixed(places));
  const slopes = profile.slice(1).map((p, i) => (p.elevationMeters-profile[i].elevationMeters)/(p.distanceMeters-profile[i].distanceMeters)*100);
  const points = profile.filter((_, i) => i % 2 === 0).map((p) => [round(p.distanceMeters/total, 6), p.x, p.y, round(p.elevationMeters*10)]);
  points.at(-1).splice(0, 4, 1, ...points[0].slice(1));
  const data = {
    circuitName: "Madring", lapLengthKm: 5.416,
    elevationChangeM: round(metadata.elevationsMeters.high-metadata.elevationsMeters.low, 1),
    maxDownhillPercent: round(Math.abs(Math.min(...slopes)), 1), maxUphillPercent: round(Math.max(...slopes), 1),
    points, turns: config.model.turns.map(({ number, name, distanceMeters }) => ({ number, name, progress: round(distanceMeters/total, 6) })),
    sectorBreaks: config.officialControlPoints.sectorBoundaries.map((p) => round(p.absoluteDistanceMeters/total, 6)),
    speedTrapProgress: round((config.model.turns[3].distanceMeters-20)/total, 6),
  };
  const terrain = {
    attribution: "Ayuntamiento de Madrid · 13.06.2026 · IGN/CNIG · OpenStreetMap",
    attributionUrl: "https://geoportal.madrid.es/", bounds: { minX: -1, minY: -1, maxX: 1, maxY: 1 },
    columns: 2, rows: 2, elevationMinM: metadata.elevationsMeters.low, elevationMaxM: metadata.elevationsMeters.high,
    values: [[metadata.elevationsMeters.low, metadata.elevationsMeters.high], [metadata.elevationsMeters.high, metadata.elevationsMeters.low]],
  };
  const model = {
    id: "madring", aliases: ["madring", "madrid", "мадринг", "мадрид", "ifema madrid", "spanish grand prix", "гран-при испании"],
    camera: { centerY: 0, rotationDeg: 40, scale: 1, tiltDeg: 10, verticalExaggeration: 1 },
    data: "__DATA__", terrain: "__TERRAIN__",
    rendering: { contourIntervalM: 5, curbTurnNumbers: data.turns.map((t) => t.number), gravelTurnNumbers: [], runoffTurnNumbers: data.turns.map((t) => t.number), turnLabelOffsets: Object.fromEntries(data.turns.map((t) => [t.number, [0, 0]])) },
    webgl: { assetPath: `/f1/tracks/3d/madring.glb?v=${assetRevision}`, previewPath: "/f1/tracks/3d/madring-preview.webp", turnCount: 22, elevationDatumLabel: "м", camera: { fitHeight: 1900, fitWidth: 2500, lookAtY: 36, radius: 3400 } },
  };
  const output = `import type { TrackModelDefinition } from "@/data/track-model-types";\n\n// Generated by the Madring Blender pipeline. Native metre geometry; no vertical exaggeration.\nexport const MADRING_MODEL = ${JSON.stringify(data, null, 2)} as const;\n\nexport const MADRING_TERRAIN = ${JSON.stringify(terrain, null, 2)} as const;\n\nexport const MADRING_TRACK_MODEL = ${JSON.stringify(model, null, 2).replace('"__DATA__"', "MADRING_MODEL").replace('"__TERRAIN__"', "MADRING_TERRAIN")} satisfies TrackModelDefinition;\n`;
  await writeFile(outputPath, output);
  return { outputPath, pointCount: points.length };
}
import { createHash } from "node:crypto";
