import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const round = (value, digits = 4) => Number(value.toFixed(digits));

export async function writeMiamiClientModel({ configPath, metadataPath }) {
  const [config, metadata, asset, preview] = await Promise.all([
    readFile(configPath, "utf8").then(JSON.parse), readFile(metadataPath, "utf8").then(JSON.parse),
    readFile(path.join(root, "public/f1/tracks/3d/miami.glb")),
    readFile(path.join(root, "public/f1/tracks/3d/miami-preview.webp")),
  ]);
  const line = config.model.centerline;
  const cumulative = [0];
  for (let i = 1; i < line.length; i++) cumulative.push(cumulative.at(-1) + Math.hypot(line[i][0] - line[i-1][0], line[i][1] - line[i-1][1]));
  const total = cumulative.at(-1);
  const profile = metadata.elevationProfile;
  const points = profile.map(({ distanceMeters, elevationMeters }, i) => {
    const hi = Math.max(1, cumulative.findIndex((d) => d >= Math.min(distanceMeters, total)));
    const t = Math.min(1, (distanceMeters - cumulative[hi-1]) / (cumulative[hi] - cumulative[hi-1]));
    const p = line[hi].map((v, axis) => line[hi-1][axis] + (v-line[hi-1][axis])*t);
    return [round(i/(profile.length-1),6), round(p[0]-config.model.center.x), round(p[1]-config.model.center.y), round(elevationMeters*10)];
  });
  points.at(-1).splice(0,4,1,...points[0].slice(1));
  const slopes = profile.slice(1).map((p,i) => (p.elevationMeters-profile[i].elevationMeters)/(p.distanceMeters-profile[i].distanceMeters)*100);
  const turns = config.model.turns.map(({ number, distanceMeters }) => ({ number, progress: round(distanceMeters/total,6) }));
  const data = {
    circuitName: "Miami International Autodrome", lapLengthKm: 5.412,
    elevationChangeM: round(metadata.elevationsMeters.high-metadata.elevationsMeters.low,1),
    maxDownhillPercent: round(Math.abs(Math.min(...slopes)),1), maxUphillPercent: round(Math.max(...slopes),1),
    points, turns, sectorBreaks: metadata.sectorBoundaryDistancesMeters.map((d) => round(d/total,6)),
    speedTrapProgress: round(config.officialControlPoints.speedTrapDistanceMeters/total,6),
  };
  const terrain = {
    attribution: "© OpenStreetMap · Miami-Dade County · USGS 3DEP · FIA 2026",
    attributionUrl: "/f1/tracks/3d/miami-metadata.json",
    bounds: { minX: -900, minY: -550, maxX: 900, maxY: 550 }, columns: 2, rows: 2,
    elevationMinM: metadata.elevationsMeters.low, elevationMaxM: metadata.elevationsMeters.high,
    values: [[metadata.elevationsMeters.low,metadata.elevationsMeters.high],[metadata.elevationsMeters.high,metadata.elevationsMeters.low]],
  };
  const revision = (buffer) => createHash("sha256").update(buffer).digest("hex").slice(0,12);
  const model = {
    id: "miami", aliases: ["miami international autodrome","miami autodrome","miami","майами","miami grand prix","гран-при майами"],
    data: "__DATA__", terrain: "__TERRAIN__",
    camera: { centerY: 0, rotationDeg: -38, scale: 1, tiltDeg: 10, verticalExaggeration: 1 },
    rendering: { contourIntervalM: 2, curbTurnNumbers: turns.map((t) => t.number), gravelTurnNumbers: [], runoffTurnNumbers: [], turnLabelOffsets: Object.fromEntries(turns.map((t) => [t.number,[0,0]])) },
    webgl: { assetPath: `/f1/tracks/3d/miami.glb?v=${revision(asset)}`, previewPath: `/f1/tracks/3d/miami-preview.webp?v=${revision(preview)}`,
      turnCount: 19, elevationDatumLabel: "м NAVD88", camera: { fitWidth: 2950, narrowFitWidth: 2250, fitHeight: 1350, lookAtY: 8, radius: 1900 } },
  };
  await writeFile(path.join(root,"src/data/miami-model.ts"), `import type { TrackModelDefinition } from "@/data/track-model-types";\n\n// Generated by pnpm track:3d:build miami. Native UTM metres, NAVD88, no vertical exaggeration.\nexport const MIAMI_MODEL = ${JSON.stringify(data,null,2)} as const;\n\nexport const MIAMI_TERRAIN = ${JSON.stringify(terrain,null,2)} as const;\n\nexport const MIAMI_TRACK_MODEL = ${JSON.stringify(model,null,2).replace('"__DATA__"',"MIAMI_MODEL").replace('"__TERRAIN__"',"MIAMI_TERRAIN")} satisfies TrackModelDefinition;\n`);
}
